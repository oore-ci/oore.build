import type {
  BuildPlatform,
  ExportPipelineYamlRequest,
  ExportPipelineYamlResponse,
  TriggerConfig,
} from '@oore/client/models'

/**
 * The demo's stand-in for `POST /v1/pipelines/export-yaml`. It follows the
 * daemon's generator closely enough to look real; the daemon is the one
 * that plans the file and checks it against the form.
 */

const DEFAULT_BUILDS = {
  android: 'flutter build apk --release',
  ios: 'flutter build ios --release --no-codesign',
  macos: 'flutter build macos --release',
} satisfies Record<BuildPlatform, string>

const DEFAULT_ARTIFACTS = {
  android: [
    'build/app/outputs/flutter-apk/*.apk',
    'build/app/outputs/bundle/**/*.aab',
  ],
  ios: ['build/ios/ipa/*.ipa'],
  macos: ['build/macos/Build/Products/Release/*.app'],
} satisfies Record<BuildPlatform, Array<string>>

const TITLES = {
  android: 'Android',
  ios: 'iOS',
  macos: 'macOS',
} satisfies Record<BuildPlatform, string>

const KNOWN_STEPS = new Map([
  ['flutter pub get', 'Get packages'],
  ['flutter analyze', 'Analyze'],
  ['flutter test', 'Run tests'],
])

function scalar(value: string): string {
  const plain =
    /^[A-Za-z_./$]/.test(value) &&
    // YAML 1.1 booleans, nulls and special floats are quoted, as the daemon does.
    !/: | #|:$|^(true|false|yes|no|y|n|on|off|null|~|[-+]?\.inf|\.nan)$/i.test(
      value,
    ) &&
    value.trim() === value
  return plain ? value : `'${value.replaceAll("'", "''")}'`
}

function list(indent: number, items: Array<string>): Array<string> {
  return items.map((item) => `${' '.repeat(indent)}- ${scalar(item)}`)
}

type OnResult =
  | { ok: true; lines: Array<string> }
  | { ok: false; reason: string }

export function onLines(triggers: TriggerConfig): OnResult {
  const listed = (event: string) =>
    triggers.events.length === 0 || triggers.events.includes(event)
  const branches = triggers.branches
  const tags = triggers.tags ?? []
  if ((triggers.paths_ignore ?? []).length > 0) {
    return {
      ok: false,
      reason: 'they ignore changed paths, which `on` cannot express',
    }
  }
  if (listed('pull_request') && branches.length > 0) {
    return {
      ok: false,
      reason:
        "their branch filter matches a pull request's source branch, while on.pull_request.branches matches the branch it targets",
    }
  }
  const everyRef = branches.length === 0 && tags.length === 0
  const lines: Array<string> = []
  if (listed('push') && everyRef) lines.push('  push: true')
  if (listed('push') && branches.length > 0) {
    lines.push('  push:', '    branches:', ...list(6, branches))
  }
  if (listed('pull_request') && everyRef) lines.push('  pull_request: true')
  const tag = listed('tag_push') ? (everyRef ? ['*'] : tags) : []
  if (tag.length > 0) lines.push('  tag:', ...list(4, tag))
  const paths = triggers.paths ?? []
  const branchEvents = lines.some(
    (line) => line.startsWith('  push') || line.startsWith('  pull_request'),
  )
  if (paths.length > 0 && branchEvents) {
    lines.push('  paths:', ...list(4, paths))
  }
  return { ok: true, lines: lines.length > 0 ? ['on:', ...lines] : ['on: {}'] }
}

export function demoExportYaml(
  body: ExportPipelineYamlRequest,
): ExportPipelineYamlResponse {
  const config = body.execution_config
  if (config.platforms.length === 0) {
    return {
      valid: false,
      errors: ['execution_config.platforms must include at least one platform'],
      warnings: [],
      notes: [],
    }
  }
  const play = body.google_play?.enabled ? body.google_play : undefined
  const store = body.app_store?.enabled ? body.app_store : undefined
  const notes: Array<string> = []
  const out: Array<string> = [
    "# Generated by Oore from the pipeline's settings. It runs the same commands in",
    '# the same order.',
    "# Commit it as .oore.yaml at the repository root, or at the pipeline's config",
    "# path. Builds then read it from the repository instead of the pipeline's",
    '# Build settings.',
    'version: 2',
    '',
  ]
  if (config.flutter_version?.trim()) {
    out.push(
      'app:',
      '  # A .fvmrc file still takes precedence.',
      `  flutter: '${config.flutter_version.trim()}'`,
    )
  } else {
    out.push(
      "# No Flutter version is pinned: a .fvmrc file, else the runner's Flutter,",
      '# decides. Set app.flutter to pin one.',
    )
  }

  const defaults = [
    ...new Set(config.platforms.flatMap((p) => DEFAULT_ARTIFACTS[p])),
  ]
  const artifacts = [...new Set(config.artifact_patterns.map((p) => p.trim()))]
  const explicit = artifacts.join('\n') !== defaults.join('\n')
  out.push('', 'targets:')
  config.platforms.forEach((platform, index) => {
    const override = config.platform_commands?.[platform]
    const args = config.platform_build_args?.[platform] ?? []
    let build = override || [DEFAULT_BUILDS[platform], ...args].join(' ')
    out.push(`  ${platform}:`)
    out.push(
      override
        ? `    # The pipeline's ${TITLES[platform]} build command.`
        : `    # Oore's default ${TITLES[platform]} build command.`,
    )
    if (platform === 'android' && play && !override) {
      build = `${build} && ${[
        'flutter build appbundle --release',
        ...args.filter((arg) => arg !== '--split-per-abi'),
      ].join(' ')}`
      out.push(
        '    # The pipeline uploads to Google Play, so the App Bundle Play needs is',
        "    # built after the APK, as the pipeline's default Android build did.",
      )
    }
    out.push(`    build: ${scalar(build)}`)
    if (explicit && index === 0) {
      out.push(
        config.platforms.length > 1
          ? '    artifacts: &artifacts'
          : '    artifacts:',
        ...list(6, artifacts),
      )
    } else if (explicit) {
      out.push('    artifacts: *artifacts')
    }
    if (platform === 'android' && play) {
      out.push(
        '    publish:',
        "      # From the pipeline's Google Play settings, which still supply the",
        '      # service account and release notes.',
        '      play:',
        `        track: ${scalar(play.track)}`,
      )
      const percent = play.rollout_percent ?? 100
      // Always explicit, so the file keeps this rollout; 1 is everyone.
      out.push(`        rollout: ${percent < 100 ? percent / 100 : 1}`)
      out.push(`        draft: ${play.draft ?? false}`)
    }
    if (platform === 'ios' && store) {
      const groups = store.testflight_groups
      if (store.destination !== 'app_store' && groups.length === 1) {
        out.push(
          '    publish:',
          '      testflight:',
          `        group: ${scalar(groups[0])}`,
        )
      } else {
        notes.push(
          `App Store Connect uploads stay in the pipeline's Publish settings: they name ${groups.length === 0 ? 'no' : 'several'} TestFlight groups, and publish.testflight names exactly one`,
        )
      }
    }
  })
  if (play || store) {
    notes.push(
      "Store credentials and release notes stay in the pipeline's Publish settings; the file's publish says where each build uploads. Keep the store's \"Upload after each build\" on: turned off later, the publish step fails",
    )
  }

  const names = new Set(config.platforms.map((p) => `Build ${TITLES[p]}`))
  const step = (run: string) => {
    const base = KNOWN_STEPS.get(run) ?? run.split('\n')[0].slice(0, 60)
    let name = base
    for (let n = 2; names.has(name); n++) name = `${base} (${n})`
    names.add(name)
    return [`  - name: ${scalar(name)}`, `    run: ${scalar(run)}`]
  }
  out.push(
    '',
    'steps:',
    "  # Oore runs `flutter pub get` before the pipeline's own commands.",
    ...step('flutter pub get'),
    ...config.commands.pre_build.flatMap(step),
    '  # The target builds run here.',
    '  - build',
  )
  const warnings: Array<string> = []
  if (config.commands.build.some((run) => run.includes('flutter build'))) {
    warnings.push(
      "A Build command runs `flutter build`. As a step after the target builds it no longer gets Android signing, the iOS export settings or the dart-define file Oore adds to target builds; move that build into a target's `build` instead",
    )
  }
  if (config.commands.build.length > 0) {
    out.push(
      "  # From the pipeline's Build commands, which ran after the platform builds.",
      '  # Version 2 builds only through targets, so they run as steps right after',
      '  # them.',
    )
  }
  out.push(
    ...config.commands.build.flatMap(step),
    ...config.commands.post_build.flatMap(step),
  )

  const env = config.env ?? []
  if (env.length > 0) {
    out.push(
      '',
      "# Copied from the pipeline's environment variables. Anyone who can read the",
      '# repository can read these values: keep sensitive ones in secrets and',
      '# reference them as ${{ secrets.NAME }}.',
      'env:',
      ...env.map(({ key, value }) => `  ${key}: ${scalar(value)}`),
    )
  }

  if (body.trigger_config) {
    const on = onLines(body.trigger_config)
    if (!on.ok) {
      notes.push(
        `The file has no \`on\`, so the pipeline's trigger settings keep deciding which webhooks start builds: ${on.reason}`,
      )
    } else {
      out.push(
        '',
        "# From the pipeline's trigger settings. `on` replaces them for push, pull",
        '# request and tag webhooks; schedules and manual builds still come from the',
        '# pipeline.',
        ...on.lines,
      )
    }
    if ((body.trigger_config.schedules ?? []).length > 0) {
      notes.push("Schedules stay in the pipeline's trigger settings")
    }
  }

  const extra: Array<string> = []
  if (config.build_number_offset) {
    extra.push(`build_number_offset: ${config.build_number_offset}`)
  }
  if ((config.runs_on ?? []).length > 0) {
    extra.push(`runs_on: [${(config.runs_on ?? []).join(', ')}]`)
  }
  if (config.isolation === 'vm') extra.push('isolation: vm')
  if (extra.length > 0) out.push('', ...extra)

  return {
    valid: true,
    errors: [],
    yaml: `${out.join('\n')}\n`,
    warnings,
    notes,
  }
}
