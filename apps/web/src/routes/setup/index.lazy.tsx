import { createLazyFileRoute, useNavigate } from '@tanstack/react-router'
import { useCallback, useEffect, useRef } from 'react'
import { useForm } from 'react-hook-form'
import { zodResolver } from '@hookform/resolvers/zod'
import * as z from 'zod'
import { Button } from '@/components/ui/button'
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from '@/components/ui/form'
import { Input } from '@/components/ui/input'
import { Alert, AlertDescription, AlertTitle } from '@/components/ui/alert'
import { useSetupStatus, useVerifyBootstrapToken } from '@/hooks/use-setup'
import { useSetupStore } from '@/stores/setup-store'
import { getApiErrorMessage } from '@/lib/api-client/api-error'
import { PageMeta } from '@/lib/seo'
import { useBootstrapStepTransition } from '@/hooks/use-setup-route-transitions'
import { SetupStepError } from '@/components/setup-route-components'
import type { BootstrapTokenVerifyResponse } from '@oore/client/models'
import { Text } from '@/components/layout/text'

const bootstrapTokenSchema = z.object({
  token: z.string().min(1, 'Bootstrap token is required'),
})

type BootstrapTokenForm = z.infer<typeof bootstrapTokenSchema>

export const Route = createLazyFileRoute('/setup/')({
  component: BootstrapTokenStep,
  errorComponent: SetupStepError,
})

export function BootstrapTokenStep() {
  const navigate = useNavigate()
  const sessionToken = useSetupStore((s) => s.sessionToken)
  const setSessionToken = useSetupStore((s) => s.setSessionToken)
  const setSessionExpiresAt = useSetupStore((s) => s.setSessionExpiresAt)
  const bootstrapTokenPrefill = useSetupStore((s) => s.bootstrapTokenPrefill)
  const setBootstrapTokenPrefill = useSetupStore(
    (s) => s.setBootstrapTokenPrefill,
  )
  const verifyMutation = useVerifyBootstrapToken()
  const { data: status } = useSetupStatus()

  useBootstrapStepTransition(status, sessionToken)

  return (
    <BootstrapTokenStepView
      bootstrapTokenPrefill={bootstrapTokenPrefill}
      onVerified={(response) => {
        setSessionToken(response.session_token)
        setSessionExpiresAt(response.expires_at)
        setBootstrapTokenPrefill(null)
        void navigate({
          to: '/setup/mode',
          viewTransition: { types: ['setup-forward'] },
        })
      }}
      sessionToken={sessionToken}
      verificationError={verifyMutation.error}
      verificationPending={verifyMutation.isPending}
      verifyBootstrapToken={verifyMutation.mutateAsync}
    />
  )
}

interface BootstrapTokenStepViewProps {
  bootstrapTokenPrefill: string | null
  onVerified: (response: BootstrapTokenVerifyResponse) => void
  sessionToken: string | null
  verificationError: Error | null
  verificationPending: boolean
  verifyBootstrapToken: (token: string) => Promise<BootstrapTokenVerifyResponse>
}

export function BootstrapTokenStepView({
  bootstrapTokenPrefill,
  onVerified,
  sessionToken,
  verificationError,
  verificationPending,
  verifyBootstrapToken,
}: BootstrapTokenStepViewProps) {
  const autoSubmitHandled = useRef(false)

  const form = useForm<BootstrapTokenForm>({
    resolver: zodResolver(bootstrapTokenSchema),
    defaultValues: { token: '' },
    mode: 'onSubmit',
    reValidateMode: 'onChange',
  })

  const errorMessage = verificationError
    ? getApiErrorMessage(verificationError, {
        token_expired:
          'Bootstrap token has expired. Generate a new one with the CLI.',
        token_consumed:
          'Bootstrap token has already been used. Generate a new one with the CLI.',
        invalid_token:
          'Invalid bootstrap token. Check the value and try again.',
      })
    : null

  const verifyToken = useCallback(
    async (token: string) => {
      try {
        const res = await verifyBootstrapToken(token)
        onVerified(res)
      } catch {
        // The mutation exposes the request error to the active route instance.
      }
    },
    [onVerified, verifyBootstrapToken],
  )

  useEffect(() => {
    if (autoSubmitHandled.current) return
    autoSubmitHandled.current = true

    const token = bootstrapTokenPrefill
    if (!token || sessionToken) return

    form.setValue('token', token, { shouldValidate: true })
    void verifyToken(token)
  }, [bootstrapTokenPrefill, form, sessionToken, verifyToken])

  function handleFormSubmit(data: BootstrapTokenForm) {
    void verifyToken(data.token.trim())
  }

  return (
    <Form {...form}>
      <form
        onSubmit={form.handleSubmit(handleFormSubmit)}
        className="space-y-4"
      >
        <PageMeta title="Setup Token" />
        <div className="space-y-1">
          <h2 className="text-lg font-medium">Bootstrap token</h2>
          <Text variant="muted">
            Enter the bootstrap token generated by the{' '}
            <code className="bg-muted px-1 py-0.5 text-xs">
              oore setup token
            </code>{' '}
            CLI command.
          </Text>
        </div>

        <FormField
          control={form.control}
          name="token"
          render={({ field }) => (
            <FormItem>
              <FormLabel>Token</FormLabel>
              <FormControl>
                <Input
                  type="password"
                  placeholder="Paste your bootstrap token"
                  disabled={verificationPending}
                  autoFocus
                  {...field}
                />
              </FormControl>
              <FormMessage />
            </FormItem>
          )}
        />

        {errorMessage ? (
          <Alert variant="destructive">
            <AlertTitle>Verification failed</AlertTitle>
            <AlertDescription>{errorMessage}</AlertDescription>
          </Alert>
        ) : null}

        <Button type="submit" disabled={verificationPending} className="w-full">
          {verificationPending ? 'Verifying...' : 'Verify token'}
        </Button>
      </form>
    </Form>
  )
}
